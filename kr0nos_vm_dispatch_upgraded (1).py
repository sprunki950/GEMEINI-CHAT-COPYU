def collect_locals(src: str) -> set[str]:
    cleaned = re.sub(r"--\[\[.*?\]\]", "", src, flags=re.S)
    cleaned = re.sub(r"--[^\n]*", "", cleaned)
    cleaned = re.sub(r'"(?:\\.|[^"\\])*"', '""', cleaned)
    cleaned = re.sub(r"'(?:\\.|[^'\\])*'", "''", cleaned)
    names: set[str] = set()
    for m in re.finditer(r"\blocal\s+function\s+([A-Za-z_][A-Za-z0-9_]*)", cleaned):
        names.add(m.group(1))
    for m in re.finditer(
        r"\blocal\s+([A-Za-z_][A-Za-z0-9_]*(?:\s*,\s*[A-Za-z_][A-Za-z0-9_]*)*)", cleaned
    ):
        for n in re.findall(r"[A-Za-z_][A-Za-z0-9_]*", m.group(1)):
            names.add(n)
    for m in re.finditer(r"\bfunction\s+([A-Za-z_][A-Za-z0-9_]*)", cleaned):
        names.add(m.group(1))
    return {n for n in names if n not in LUA_KW and n not in SAFE}

def rename_locals(src: str, mapping: dict) -> str:
    if not mapping:
        return src
    names = sorted(mapping, key=len, reverse=True)
    name_re = re.compile(r"\b(" + "|".join(re.escape(n) for n in names) + r")\b")
    splitter = re.compile(
        r"(--\[\[.*?\]\]|--[^\n]*|\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'|\[\[.*?\]\])",
        re.S,
    )
    parts = splitter.split(src)
    out = []
    for i, part in enumerate(parts):
        if i % 2 == 1:
            out.append(part)
            continue

        def repl(m, part=part):
            if m.start() > 0 and part[m.start() - 1] in ".:":
                return m.group(0)
            return mapping.get(m.group(0), m.group(0))

        out.append(name_re.sub(repl, part))
    return "".join(out)

def lua_str(s: str) -> str:
    """Escape for double-quoted Lua string."""
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\0", "\\0")
    )

def generate_shell(src: str, level: int = 2) -> str:
    global _USED, _ALPHA

    # Keep identifiers already allocated while renaming the input. This prevents
    # generated loader names from colliding with renamed user identifiers.

    # Per-build alphabet permutation: each output gets a different Base85 mapping.
    alphabet = list("".join(chr(c) for c in range(33, 127) if c not in (34, 61, 91, 92, 93))[:85])
    random.shuffle(alphabet)
    _ALPHA = "".join(alphabet)

    key = bytes(random.randint(1, 255) for _ in range(16))
    key_mask = bytes(random.randint(1, 255) for _ in range(16))
    masked_key = bytes(k ^ m for k, m in zip(key, key_mask))
    seed = random.randint(1, 255)
    seed2 = random.randint(1, 255)
    seed3 = random.randint(1, 255)
    px = random.randint(1, 250)
    # Every build gets a unique nonlinear byte-substitution permutation.
    sbox_list = list(range(256))
    random.shuffle(sbox_list)
    sbox = bytes(sbox_list)
    inv_sbox = [0] * 256
    for _idx, _value in enumerate(sbox_list):
        inv_sbox[_value] = _idx

    raw = src.encode("utf-8")
    payload = b"SG\x00\x00" + struct.pack("<I", len(raw)) + raw
    enc = encrypt(payload, key, seed, seed2, seed3, px, sbox)
    # Position-dependent Base85 digit rotation parameters are randomized per build.
    b85_salt = random.randrange(85)
    b85_step = random.randrange(1, 85)
    blob = b85(enc, b85_salt, b85_step)

    # Resonance-style checksum constants
    c_init = random.randint(10**8, 10**9)
    c_mul = random.randint(100, 400)
    c_add = random.randint(100, 999)
    c_expect = checksum(blob, c_mul, c_add, c_init)

    # Names
    N = {k: rnd() for k in [
        "blob", "env", "cs", "i", "trap", "entry", "bx", "A", "inv", "d",
        "u", "n", "t", "ch", "v", "ks", "st", "x", "y", "k", "rot", "a1",
        "b0", "states", "nn", "slen", "src", "loader", "fn", "err", "ok",
        "res", "genv", "key", "pc", "term", "chk", "rg", "ts", "sf", "oc",
        "wrap", "inner", "ret", "parts",
    ]}

    # Store the key masked; the loader reconstructs it at runtime.
    inv_sbox_lit = "{" + ",".join(str(v) for v in inv_sbox) + "}"
    key_lit = ",".join(str(b) for b in masked_key)
    mask_lit = "{" + ",".join(str(b) for b in key_mask) + "}"
    # Split alphabet into char codes built at runtime (harder to grep)
    alpha_codes = ",".join(str(ord(c)) for c in _ALPHA)

    # Build loader in Resonance style
    # return(function(BLOB, ENV) ... end)("blob", {}):Entry()()
    L: list[str] = []
    a = L.append

    a(f"return(function(...) local {N['blob']},{N['env']}=... ")
    # Sample-inspired runtime integrity checks. These check that core globals
    # remain stable while the wrapper is decoding; they do not claim to prevent
    # all reverse engineering or tampering.
    guard_type, guard_pcall, guard_error, guard_math = rnd(), rnd(), rnd(), rnd()
    a(f"local {guard_type},{guard_pcall},{guard_error},{guard_math}=type,pcall,error,math")
    a(f"if type~={guard_type} or pcall~={guard_pcall} or error~={guard_error} or math~={guard_math} then error('',0) end")
    # Checksum anti-tamper (Resonance style nil trap)
    a(f"local {N['cs']}={c_init}")

    # Optional decoys use table-driven rolling fingerprints rather than the old
    # `local name = (number * number) % ...` pattern. 30% of generated decoys
    # use a Moonveil-inspired integrity-check shape; this is a stylistic blend,
    # not a claim that this output was produced by Moonveil itself.
    decoy_count = max(0, min(int(level), 5)) * 3
    for decoy_idx in range(decoy_count):
        qn, tab, acc, ix, step = rnd(), rnd(), rnd(), rnd(), rnd()
        values = [random.randint(1, 255) for _ in range(random.randint(5, 9))]
        table_lit = "{" + ",".join(map(str, values)) + "}"
        mod = random.choice([65521, 65519, 65497, 65479])
        mul = random.randint(17, 251)
        add = random.randint(3, 97)
        expected = 0
        for pos, value in enumerate(values, 1):
            expected = (expected * mul + value + pos * add) % mod
        if decoy_idx < max(1, int(decoy_count * 0.30 + 0.5)):
            # Moonveil-inspired 30%: captured primitive references and a
            # lightweight integrity-shaped branch, kept unreachable.
            typ, pcall_name = rnd(), rnd()
            a(f"if false then local {typ},{pcall_name}=type,pcall; if type~={typ} or pcall~={pcall_name} then error('',0) end; local {tab}={table_lit}; local {acc}=0; for {ix}=1,#{tab} do {acc}=({acc}*{mul}+{tab}[{ix}]+{ix}*{add})%{mod} end; if {acc}~={expected} then error('',0) end end")
        else:
            # Table-driven modular fingerprint decoy: no multiply-two-literals
            # local initialization, and no execution because the guard is false.
            a(f"if false then local {tab}={table_lit}; local {acc}=0; for {ix}=1,#{tab} do {acc}=({acc}*{mul}+{tab}[{ix}]+{ix}*{add})%{mod} end; local {qn}=({acc}=={expected}); if {qn} then {step}={acc} end end")

    a(f"for {N['i']}=1,#{N['blob']} do")
    a(f"{N['cs']}=({N['cs']}*{c_mul}+string.byte({N['blob']},{N['i']})+{N['i']}*{c_add})%2147483647")
    a("end")
    a(f"if {N['cs']}~={c_expect} then local {N['trap']}=nil local _={N['trap']}.p1y4 end")

    # Secondary checksum
    a(f"local {N['wrap']}=({N['cs']}+#{N['blob']}*{random.randint(100,500)}+string.byte({N['blob']},1)*{random.randint(100,900)})%2147483647")

    # Entry method attached to env table
    a(f"function {N['env']}.{N['entry']}()")
    a(f"local {N['inner']}=(function()")

    # bxor
    a(f"local function {N['bx']}(a,b)")
    a("a=math.floor(a)%256 b=math.floor(b)%256 local r=0 local p=1 local i=0")
    a("while i<8 do i=i+1 if a%2~=b%2 then r=r+p end a=math.floor(a/2) b=math.floor(b/2) p=p*2 end")
    a("return r end")

    # Build alphabet from codes
    a(f"local {N['A']}=string.char({alpha_codes})")
    a(f"local {N['inv']}={{}}")
    a(f"for {N['i']}=1,#{N['A']} do {N['inv']}[{N['A']}:sub({N['i']},{N['i']})]={N['i']}-1 end")

    # Base85 decode blob
    a(f"local {N['d']}={{}} local {N['u']}=1 local {N['n']}=0 local {N['t']}=0")
    a(f"while {N['u']}<=#{N['blob']} do")
    a(f"local {N['ch']}={N['blob']}:sub({N['u']},{N['u']}) {N['u']}={N['u']}+1")
    a(f"local {N['v']}={N['inv']}[{N['ch']}]")
    a(f"if {N['v']} then {N['v']}=({N['v']}-(({N['u']}-2)*{b85_step}+{b85_salt})%85)%85 end")
    a(f"if {N['v']} then {N['n']}={N['n']}*85+{N['v']} {N['t']}={N['t']}+1")
    a(f"if {N['t']}==5 then")
    a(f"{N['d']}[#{N['d']}+1]=math.floor({N['n']}/16777216)%256")
    a(f"{N['d']}[#{N['d']}+1]=math.floor({N['n']}/65536)%256")
    a(f"{N['d']}[#{N['d']}+1]=math.floor({N['n']}/256)%256")
    a(f"{N['d']}[#{N['d']}+1]={N['n']}%256")
    a(f"{N['n']}=0 {N['t']}=0 end end end")
    a(f"if {N['t']}>0 then for ii={N['t']},4 do {N['n']}={N['n']}*85+84 end")
    a(f"local yy=math.max({N['t']}-1,1)")
    a(f"local zz={{math.floor({N['n']}/16777216)%256,math.floor({N['n']}/65536)%256,math.floor({N['n']}/256)%256,{N['n']}%256}}")
    a(f"for ii=1,yy do {N['d']}[#{N['d']}+1]=zz[ii] end end")

    # Key + schedule
    a(f"local {N['key']}={{{key_lit}}}")
    a(f"local km={mask_lit} for i=1,#{N['key']} do {N['key']}[i]={N['bx']}({N['key']}[i],km[i]) end")
    a(f"local {N['ks']}={{}} local ss={seed}%256")
    a(f"for i=0,31 do ss=(ss*73+{N['key']}[(i%#{N['key']})+1]+i*19)%256 {N['ks']}[i+1]=ss end")

    # Randomized opcode-dispatch VM for the loader's inverse-transform pipeline.
    # This virtualizes the decoding stages, not the user's Lua source itself.
    ops = random.sample(range(17, 240), 7)
    op_key, op_state, op_nibble, op_pos, op_pair, op_reverse, op_forward = ops
    vm_name, pc_name, handlers_name, handler_name = (rnd() for _ in range(4))
    a(f"local {handlers_name}={{}}")
    a(f"{handlers_name}[{op_key}]=function() local sb={inv_sbox_lit} for i=1,#{N['d']} do {N['d']}[i]=sb[{N['d']}[i]+1] {N['d']}[i]={N['bx']}({N['d']}[i],{N['key']}[(i-1)%#{N['key']}+1]) end return {op_state} end")
    a(f"{handlers_name}[{op_state}]=function() local st={seed3}%256 for i=1,#{N['d']} do local x={N['d']}[i] {N['d']}[i]={N['bx']}(x,st) st=(st*31+x+7)%256 end return {op_nibble} end")
    a(f"{handlers_name}[{op_nibble}]=function() for i=1,#{N['d']} do local x={N['d']}[i] {N['d']}[i]=((x%16)*16)+math.floor(x/16)%16 end return {op_pos} end")
    a(f"{handlers_name}[{op_pos}]=function() for i=1,#{N['d']} do {N['d']}[i]={N['bx']}({N['d']}[i],({px}+(i-1)*13)%256) end return {op_pair} end")
    a(f"{handlers_name}[{op_pair}]=function() local i=1 while i<#{N['d']} do local aa,bb={N['d']}[i],{N['d']}[i+1]")
    a(f"local rot=((bb*8)+math.floor(bb/32))%256 local a1={N['bx']}(aa,rot)")
    a(f"local ksi={N['ks']}[math.floor((i-1)/2)%32+1] local b0={N['bx']}({N['bx']}(bb,ksi),a1)")
    a(f"{N['d']}[i]=(a1-b0)%256 {N['d']}[i+1]=b0 i=i+2 end return {op_reverse} end")
    a(f"{handlers_name}[{op_reverse}]=function() local nn=#{N['d']} local states={{}} local st=({seed2}*31+47)%256")
    a(f"for i=nn,1,-1 do states[i]=st st={N['bx']}({N['bx']}(st,{N['d']}[i]),((i-1)*17)%256) end")
    a(f"for i=nn,1,-1 do local k={N['ks']}[((i-1)*3)%32+1] local rot=((k*2)+math.floor(k/128))%256")
    a(f"{N['d']}[i]={N['bx']}({N['d']}[i],{N['bx']}(states[i],rot)) end return {op_forward} end")
    a(f"{handlers_name}[{op_forward}]=function() local st={seed}%256 for i=1,#{N['d']} do local k={N['ks']}[(i-1)%32+1] local x={N['d']}[i]")
    a(f"{N['d']}[i]={N['bx']}(x,{N['bx']}(st,k)) st=(st+x+k*13+7)%256 end return 0 end")
    a(f"local {pc_name}={op_key} while {pc_name}~=0 do local {handler_name}={handlers_name}[{pc_name}] if not {handler_name} then error('SolarHub: invalid VM opcode') end {pc_name}={handler_name}() end")

    # Magic SG
    a(f"if not({N['d']}[1]==83 and {N['d']}[2]==71) then local {N['trap']}=nil local _={N['trap']}.x9 end")
    a(f"local {N['slen']}={N['d']}[5]+{N['d']}[6]*256+{N['d']}[7]*65536+{N['d']}[8]*16777216")
    a(f"if {N['slen']}<0 or {N['slen']}>#{N['d']}-8 then local {N['trap']}=nil local _={N['trap']}.x9 end")
    a(f"local t={{}} for i=1,{N['slen']} do t[i]=string.char({N['d']}[8+i] or 0) end")
    a(f"local {N['src']}=table.concat(t)")
    # wipe
    a(f"for i=1,#{N['d']} do {N['d']}[i]=0 end")

    # Env + loadstring
    a(f"local {N['genv']}=(type(getgenv)==\"function\" and getgenv())or(type(getrenv)==\"function\" and getrenv())or _G")
    a(f"for _,nm in ipairs({{\"game\",\"workspace\",\"Instance\",\"Color3\",\"UDim2\",\"Vector3\",\"CFrame\",\"Enum\",\"task\",\"wait\",\"tick\",\"typeof\",\"spawn\",\"setfpscap\",\"print\",\"warn\",\"error\",\"pcall\",\"pairs\",\"ipairs\",\"type\",\"tostring\",\"tonumber\",\"string\",\"table\",\"math\",\"bit32\",\"rawget\",\"rawset\",\"setmetatable\",\"getmetatable\",\"require\",\"loadstring\",\"load\",\"getgenv\",\"getrenv\",\"Drawing\",\"request\",\"HttpGet\",\"syn\"}}) do")
    a(f"local v=rawget({N['genv']},nm) if v==nil and _G then v=rawget(_G,nm) end if v~=nil then {N['genv']}[nm]=v end end")
    a(f"local {N['loader']}={N['genv']}.loadstring or {N['genv']}.load or loadstring or load")
    a(f"if not {N['loader']} then error(\"SolarHub: no loadstring\") end")
    a(f"local {N['fn']},{N['err']}={N['loader']}({N['src']})")
    a(f"if not {N['fn']} then {N['fn']},{N['err']}={N['loader']}({N['src']},\"SolarHub\",\"t\",{N['genv']}) end")
    a(f"{N['src']}=nil")
    a(f"if not {N['fn']} then error(\"SolarHub load: \"..tostring({N['err']})) end")
    a(f"if setfenv then pcall(setfenv,{N['fn']},{N['genv']}) end")
    a(f"local {N['ok']},{N['res']}=pcall({N['fn']})")
    a(f"if not {N['ok']} then error(\"SolarHub runtime: \"..tostring({N['res']})) end")
    a(f"return {N['res']}")
    a("end)")
    a(f"return {N['inner']}")
    a("end")
    a(f"return {N['env']}")
    # Split the encoded payload into randomized-sized string fragments.
    # table.concat reconstructs the exact blob before checksum/decode.
    chunks = []
    pos = 0
    while pos < len(blob):
        width = random.randint(73, 151)
        chunks.append(blob[pos:pos + width])
        pos += width
    blob_expr = "table.concat({" + ",".join('"' + lua_str(part) + '"' for part in chunks) + "})"
    a(f'end)({blob_expr},{{}}).{N["entry"]}()()')

    return "".join(L) if False else " ".join(L)

def obfuscate(src: str, level: int = 2, compact: bool | None = None) -> str:
    global _USED
    _USED = set()
    if compact is None:
        compact = len(src) >= 32_000
    idents = collect_locals(src)
    if compact and len(idents) > 500:
        idents = {n for n in idents if len(n) >= 3}
    mapping = {n: rnd(random.randint(3, 6)) for n in idents}
    src = rename_locals(src, mapping)
    return HEADER + generate_shell(src, level)

